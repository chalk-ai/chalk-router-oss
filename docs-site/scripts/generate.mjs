function indexTypes(f, messages, prefix) {
  for (const m of messages ?? []) {
    protoIndex.set('.' + prefix + m.name, { file: f, name: m.name });
    indexTypes(f, m.nestedType, prefix + m.name + '.');
    for (const e of m.enumType ?? []) protoIndex.set('.' + prefix + m.name + '.' + e.name, { file: f, name: e.name });
  }
}
for (const f of files) {
  indexTypes(f, f.messageType, f.package + '.');
  for (const e of f.enumType ?? []) protoIndex.set('.' + f.package + '.' + e.name, { file: f, name: e.name });
}
